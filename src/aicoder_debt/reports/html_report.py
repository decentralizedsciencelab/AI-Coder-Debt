"""HTML report generator for AI Coder Debt analysis."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from ..models import AnalysisResult


class HTMLReportGenerator:
    """Generate standalone HTML reports from analysis results."""

    def generate(self, result: "AnalysisResult") -> str:
        """Generate HTML report string.

        Args:
            result: Analysis result to format.

        Returns:
            HTML string.
        """
        # Build HTML document
        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>AI Coder Debt Analysis Report</title>
    <style>
        {self._get_styles()}
    </style>
</head>
<body>
    <div class="container">
        <header>
            <h1>AI Coder Debt Analysis Report</h1>
            <div class="meta">
                <p><strong>Project:</strong> <code>{result.project_path}</code></p>
                <p><strong>Timestamp:</strong> {result.timestamp}</p>
            </div>
        </header>

        <section class="summary">
            <h2>Metrics Summary</h2>
            {self._generate_summary_table(result)}
        </section>

        <section class="ddg">
            <h2>Deployment Dependency Graph</h2>
            {self._generate_ddg_section(result)}
        </section>

        <section class="tier1">
            <h2>Tier 1: Deployment Metrics</h2>
            {self._generate_tier1_section(result)}
        </section>

        <section class="tier2">
            <h2>Tier 2: Integration Metrics</h2>
            {self._generate_tier2_section(result)}
        </section>

        <section class="tier3">
            <h2>Tier 3: Assumption Metrics</h2>
            {self._generate_tier3_section(result)}
        </section>

        {self._generate_tier4_section(result) if result.tier4 else ""}

        <footer>
            <p>Generated by <strong>aicoder-debt</strong></p>
        </footer>
    </div>
</body>
</html>"""
        return html

